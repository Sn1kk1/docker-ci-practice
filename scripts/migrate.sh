#!/usr/bin/env bash
set -euo pipefail
umask 077
cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  set -a
  source ./.env
  set +a
fi
: "${DB_POSTGRES_PASSWORD:?Set DB_POSTGRES_PASSWORD}"
if [[ ! "$DB_POSTGRES_PASSWORD" =~ ^[[:xdigit:]]{24,}$ ]]; then
  echo 'Use a PostgreSQL password generated by openssl rand -hex 24.' >&2
  exit 1
fi

state_dir="${MIGRATION_STATE_DIR:-$PWD/../mm-practice4-state}"
mkdir -p "$state_dir"
marker="$state_dir/.migration_completed"
backup="$state_dir/mysql-${GITHUB_RUN_ID:-$(date -u +%Y%m%dT%H%M%SZ)}-${GITHUB_RUN_ATTEMPT:-1}.sql.gz"
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

legacy=(docker compose -f legacy/docker-compose.yml)
prod=(docker compose -f docker-compose.prod.yml)
export MM_VERSION=12.0.1
export COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-mm-practice4}"

pg() {
  "${prod[@]}" exec -T db-postgres psql -X -v ON_ERROR_STOP=1 -U mmuser -d mattermost "$@"
}

mysql() {
  "${legacy[@]}" exec -T db-mysql sh -c 'export MYSQL_PWD="$MYSQL_PASSWORD"; exec mysql -u"$MYSQL_USER" --batch --skip-column-names "$@" mattermost' mysql "$@"
}

ping() {
  local url="http://localhost:${MM_PORT:-8065}/api/v4/system/ping"
  local attempt response
  local expected='"status"[[:space:]]*:[[:space:]]*"OK"'
  for ((attempt = 1; attempt <= 60; attempt++)); do
    if response="$(curl --silent --fail --max-time 4 "$url")" &&
       [[ "$response" =~ $expected ]]; then
      printf '%s\n' "$response"
      return
    fi
    sleep 2
  done
  echo 'Mattermost did not return status OK before the timeout.' >&2
  return 1
}

schema_upgrade() {
  local version="$1"
  printf 'Preparing PostgreSQL schema for Mattermost %s\n' "$version"
  if ! MM_VERSION="$version" "${prod[@]}" run --rm --no-deps --entrypoint /mattermost/bin/mattermost mattermost db migrate >"$scratch/schema.log" 2>&1; then
    echo 'Mattermost db migrate failed. Details are in the private state directory.' >&2
    cp "$scratch/schema.log" "$state_dir/schema-error.log"
    return 1
  fi
}

"${prod[@]}" up -d --wait --wait-timeout 210 db-postgres
db_marker="$(pg -Atqc "SELECT to_regclass('practice4.completed') IS NOT NULL")"
if [[ -e "$marker" && "$db_marker" != t ]]; then
  echo 'The state file does not match this PostgreSQL volume. Check the Docker context and volumes.' >&2
  exit 1
fi

if [[ "$db_marker" == t ]]; then
  echo 'Migration already completed. Skipping MySQL backup, pgloader, and schema upgrade.'
else
  : "${DB_MYSQL_ROOT_PASSWORD:?Set DB_MYSQL_ROOT_PASSWORD for the first run}"
  : "${DB_MYSQL_USER_PASSWORD:?Set DB_MYSQL_USER_PASSWORD for the first run}"
  if [[ ! "$DB_MYSQL_USER_PASSWORD" =~ ^[[:xdigit:]]{24,}$ ]]; then
    echo 'Use a MySQL user password generated by openssl rand -hex 24.' >&2
    exit 1
  fi
  if [[ -z "$("${legacy[@]}" ps --status running -q db-mysql)" ]]; then
    echo 'Start legacy MySQL and populate the demo workspace first.' >&2
    exit 1
  fi

  "${legacy[@]}" stop mattermost
  echo 'Backing up MySQL before transfer.'
  "${legacy[@]}" exec -T -e DB_MYSQL_ROOT_PASSWORD db-mysql sh -c '
    export MYSQL_PWD="$DB_MYSQL_ROOT_PASSWORD"
    exec mysqldump -uroot --single-transaction --no-tablespaces --set-gtid-purged=OFF mattermost
  ' | gzip >"$scratch/mysql.sql.gz"
  gzip -t "$scratch/mysql.sql.gz"
  mv "$scratch/mysql.sql.gz" "$backup"
  printf 'Backup saved: %s\n' "$backup"

  # Keep both the exact message identity and source counts for all tables.
  mysql -e "SELECT CONCAT('SELECT ', QUOTE(LOWER(TABLE_NAME)), ', COUNT(*) FROM \`', TABLE_NAME, '\`;')
    FROM information_schema.TABLES WHERE TABLE_SCHEMA = 'mattermost' AND TABLE_TYPE = 'BASE TABLE'
    ORDER BY TABLE_NAME" >"$scratch/counts.sql"
  mysql <"$scratch/counts.sql" >"$scratch/source.tsv"
  mysql -e "SELECT CONCAT(HEX(p.Id), ':', HEX(p.Message), ':', HEX(COALESCE(p.FileIds, '')))
    FROM Posts p JOIN Channels c ON p.ChannelId=c.Id WHERE c.Type='P' ORDER BY BINARY p.Id" >"$scratch/posts.before"
  if [[ ! -s "$scratch/posts.before" ]]; then
    echo 'No messages in a private channel. Populate the demo workspace first.' >&2
    exit 1
  fi

  # This dedicated PostgreSQL target can be rebuilt only while its marker is absent.
  pg -qc 'DROP SCHEMA public CASCADE; CREATE SCHEMA public AUTHORIZATION mmuser;'
  schema_upgrade 9.5.14
  echo 'Transferring MySQL tables to the staging schema with pgloader (include drop).'
  cat >"$scratch/migration.load" <<EOF
LOAD DATABASE
 FROM mysql://mmuser:${DB_MYSQL_USER_PASSWORD}@db-mysql/mattermost
 INTO postgresql://mmuser:${DB_POSTGRES_PASSWORD}@db-postgres/mattermost
 WITH include drop, create tables, create indexes, reset sequences;
EOF
  if ! docker run --rm --platform linux/amd64 --network "${COMPOSE_PROJECT_NAME}_db" \
      -i --entrypoint pgloader mattermost/mattermost-pgloader:latest --on-error-stop /dev/stdin \
      <"$scratch/migration.load" >"$scratch/pgloader.log" 2>&1; then
    cp "$scratch/pgloader.log" "$state_dir/pgloader-error.log"
    echo 'pgloader failed. Details are in the private state directory.' >&2
    exit 1
  fi
  if grep -Eq '(^|[[:space:]])(ERROR|FATAL|KABOOM)([[:space:]]|:)' "$scratch/pgloader.log"; then
    cp "$scratch/pgloader.log" "$state_dir/pgloader-error.log"
    echo 'pgloader reported errors. Check the private state directory.' >&2
    exit 1
  fi

  {
    printf 'BEGIN;\nCREATE TEMP TABLE source_counts (table_name text PRIMARY KEY, row_count bigint);\n'
    printf '\\copy source_counts FROM STDIN\n'
    cat "$scratch/source.tsv"
    printf '\\.\n'
    cat scripts/copy-staging.sql
    printf 'COMMIT;\n'
  } | pg -q

  for version in 9.11.18 10.11.26 11.7.3 12.0.1; do
    schema_upgrade "$version"
  done
  pg -Atqc "SELECT upper(encode(convert_to(p.id,'UTF8'),'hex')) || ':' ||
    upper(encode(convert_to(p.message,'UTF8'),'hex')) || ':' ||
    upper(encode(convert_to(coalesce(p.fileids,''),'UTF8'),'hex'))
    FROM posts p JOIN channels c ON p.channelid=c.id WHERE c.type='P' ORDER BY p.id COLLATE \"C\"" >"$scratch/posts.after"
  cmp "$scratch/posts.before" "$scratch/posts.after"
  printf 'Verified private-channel post IDs, text and file references: %s rows.\n' "$(wc -l <"$scratch/posts.after" | tr -d ' ')"
  pg -qc 'DROP SCHEMA mattermost CASCADE; BEGIN; CREATE SCHEMA practice4; CREATE TABLE practice4.completed (finished_at timestamptz NOT NULL DEFAULT now()); INSERT INTO practice4.completed DEFAULT VALUES; COMMIT;' >"$scratch/finish.log" 2>&1
fi

printf 'completed\n' >"$state_dir/.migration_completed.tmp"
mv -f "$state_dir/.migration_completed.tmp" "$marker"
echo 'Deploying Mattermost 12.0.1 and removing orphan containers.'
"${prod[@]}" up -d --remove-orphans
echo 'HTTP smoke test:'
ping
"${prod[@]}" ps
